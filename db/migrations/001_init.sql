-- ═══════════════════════════════════════════════════════════════════════════
-- Aarogya Saarthi — initial schema (SQLite)
--
-- The database is a single SQLite file (see SQLITE_PATH). It is created and
-- migrated automatically by the API server on start-up:
--     node --experimental-strip-types server/api.ts
--
-- Notes
--  * SQLite has no row level security, so the isolation between ASHA
--    workers is enforced in the application layer: every query is scoped by
--    asha_worker_id and every id is checked against the authenticated user
--    (see server/lib/handlers.ts). The UNIQUE constraints and the CHECK
--    constraints below are the second line of defence.
--  * Ids are UUIDs generated by the client (offline first) or by the
--    database default below.
--  * Lists and JSON documents are stored as TEXT (JSON) - SQLite has no
--    array or jsonb type.
--  * Timestamps are ISO-8601 UTC strings, which sort correctly as text.
-- ═══════════════════════════════════════════════════════════════════════════

PRAGMA foreign_keys = ON;

-- ───────────────────────────────────────────────────────────────────────────
-- ASHA workers
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS asha_workers (
  id         TEXT PRIMARY KEY
             DEFAULT (lower(hex(randomblob(4))) || '-' ||
                      lower(hex(randomblob(2))) || '-4' ||
                      substr(lower(hex(randomblob(2))), 2) || '-' ||
                      substr('89ab', 1 + (abs(random()) % 4), 1) ||
                      substr(lower(hex(randomblob(2))), 2) || '-' ||
                      lower(hex(randomblob(6)))),
  name       TEXT NOT NULL,
  village    TEXT NOT NULL,
  phone      TEXT UNIQUE,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ───────────────────────────────────────────────────────────────────────────
-- Patients
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS patients (
  id             TEXT PRIMARY KEY
                 DEFAULT (lower(hex(randomblob(4))) || '-' ||
                          lower(hex(randomblob(2))) || '-4' ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          substr('89ab', 1 + (abs(random()) % 4), 1) ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          lower(hex(randomblob(6)))),
  asha_worker_id TEXT REFERENCES asha_workers (id) ON DELETE CASCADE,
  name           TEXT NOT NULL,
  age            INTEGER,
  gender         TEXT CHECK (gender IN ('female', 'male', 'other')),
  village        TEXT,
  created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE INDEX IF NOT EXISTS idx_patients_asha_worker_id ON patients (asha_worker_id);

-- ───────────────────────────────────────────────────────────────────────────
-- Symptom logs (voice notes + detected symptoms + triage outcome)
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS symptom_logs (
  id             TEXT PRIMARY KEY
                 DEFAULT (lower(hex(randomblob(4))) || '-' ||
                          lower(hex(randomblob(2))) || '-4' ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          substr('89ab', 1 + (abs(random()) % 4), 1) ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          lower(hex(randomblob(6)))),
  patient_id     TEXT REFERENCES patients (id) ON DELETE CASCADE,
  asha_worker_id TEXT REFERENCES asha_workers (id) ON DELETE CASCADE,
  raw_transcript TEXT,
  -- JSON array of normalised symptoms, e.g. ["fever","cough"]
  symptoms       TEXT NOT NULL DEFAULT '[]'
                 CHECK (json_valid(symptoms) AND json_type(symptoms) = 'array'),
  captured_at    TEXT NOT NULL,
  synced_at      TEXT DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  triage_result  TEXT CHECK (triage_result IN ('home_care', 'visit_phc', 'refer_immediately')),
  -- JSON object: { headline_hi, headline_en, reasoning, source }
  triage_advice  TEXT CHECK (triage_advice IS NULL OR json_valid(triage_advice)),
  created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE INDEX IF NOT EXISTS idx_symptom_logs_patient_captured
  ON symptom_logs (patient_id, captured_at DESC);
CREATE INDEX IF NOT EXISTS idx_symptom_logs_worker ON symptom_logs (asha_worker_id);

-- ───────────────────────────────────────────────────────────────────────────
-- Prescriptions (OCR of a paper prescription slip)
-- The captured photo is stored in the database itself, so a single SQLite
-- file is all that is needed to run the whole app.
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS prescriptions (
  id             TEXT PRIMARY KEY
                 DEFAULT (lower(hex(randomblob(4))) || '-' ||
                          lower(hex(randomblob(2))) || '-4' ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          substr('89ab', 1 + (abs(random()) % 4), 1) ||
                          substr(lower(hex(randomblob(2))), 2) || '-' ||
                          lower(hex(randomblob(6)))),
  patient_id     TEXT REFERENCES patients (id) ON DELETE CASCADE,
  asha_worker_id TEXT REFERENCES asha_workers (id) ON DELETE CASCADE,
  image_url      TEXT,
  image_mime     TEXT,
  image_blob     BLOB,
  image_bytes    INTEGER,
  ocr_text       TEXT,
  ocr_confidence REAL CHECK (ocr_confidence IS NULL OR
                              (ocr_confidence >= 0 AND ocr_confidence <= 100)),
  captured_at    TEXT NOT NULL,
  synced_at      TEXT DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  created_at     TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE INDEX IF NOT EXISTS idx_prescriptions_patient ON prescriptions (patient_id);
CREATE INDEX IF NOT EXISTS idx_prescriptions_worker ON prescriptions (asha_worker_id);

-- ───────────────────────────────────────────────────────────────────────────
-- Sync queue (server side mirror of what devices are holding offline)
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS sync_queue (
  id               TEXT PRIMARY KEY
                   DEFAULT (lower(hex(randomblob(4))) || '-' ||
                            lower(hex(randomblob(2))) || '-4' ||
                            substr(lower(hex(randomblob(2))), 2) || '-' ||
                            substr('89ab', 1 + (abs(random()) % 4), 1) ||
                            substr(lower(hex(randomblob(2))), 2) || '-' ||
                            lower(hex(randomblob(6)))),
  client_record_id TEXT UNIQUE,
  record_type      TEXT NOT NULL
                   CHECK (record_type IN ('symptom_log', 'prescription', 'patient')),
  asha_worker_id   TEXT REFERENCES asha_workers (id) ON DELETE CASCADE,
  payload          TEXT NOT NULL DEFAULT '{}'
                   CHECK (json_valid(payload) AND json_type(payload) = 'object'),
  status           TEXT NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'synced', 'failed')),
  error_message    TEXT,
  created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE INDEX IF NOT EXISTS idx_sync_queue_worker_status
  ON sync_queue (asha_worker_id, status);
